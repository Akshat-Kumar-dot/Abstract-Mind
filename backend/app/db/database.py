"""Storage: PostgreSQL in production, SQLite for local runs and tests.

Set DATABASE_URL (postgres://… or postgresql://…, as Render, Neon and Supabase
give it) to use Postgres. Without it the app keeps everything in one SQLite
file at DB_PATH, so a laptop needs no database server.

The rest of the app writes one dialect, and this module adapts it:
  - `?` placeholders (turned into `%s` for Postgres)
  - rows read by column name or position, or iterated as values
  - `con.insert(...)` for a new row's id (`RETURNING id` on both)

The schema is versioned and migrated the first time each database is opened:
SQLite keeps the version in PRAGMA user_version, Postgres in schema_version.
On SQLite secure_delete is on, so deleted rows are overwritten instead of
lingering in the file's free pages.

What the database can hold about a person: their email and display name, their
Google account id, a hash of their auth key, their PBKDF2 salt, their data key
in encrypted form, session-token hashes, and their saved documents as
ciphertext with sizes, star flags and timestamps. It never holds a password, a
usable key, an uploaded file or any readable extraction.
"""
from __future__ import annotations

import os
import sqlite3
import threading
from contextlib import contextmanager
from pathlib import Path
from typing import Any, Iterator, Optional, Sequence

from ..settings import get_settings

SCHEMA_VERSION = 3

_SQLITE_SCHEMA = """
CREATE TABLE users (
  id             INTEGER PRIMARY KEY,
  email          TEXT UNIQUE,              -- NULL for guest accounts
  name           TEXT NOT NULL DEFAULT '',
  is_guest       INTEGER NOT NULL DEFAULT 0,
  auth_hash      BLOB,                     -- scrypt of the browser's auth key
  auth_salt      BLOB,
  kdf_salt       BLOB,                     -- the browser's PBKDF2 salt (not secret)
  kdf_iterations INTEGER,
  wrapped_key    TEXT,                     -- data key encrypted in the browser; unreadable here
  google_sub     TEXT UNIQUE,              -- Google account id, for "Continue with Google"
  created_at     REAL NOT NULL,
  updated_at     REAL NOT NULL
);
CREATE TABLE sessions (
  token_hash TEXT PRIMARY KEY,             -- sha256 of the cookie value
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at REAL NOT NULL,
  expires_at REAL NOT NULL
);
CREATE INDEX sessions_user ON sessions(user_id);
CREATE TABLE documents (
  id         TEXT PRIMARY KEY,             -- random, so ids reveal nothing
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  meta       TEXT NOT NULL,                -- ciphertext: title, kind, byline, counts
  body       TEXT NOT NULL,                -- ciphertext: the full extraction
  size       INTEGER NOT NULL,
  starred    INTEGER NOT NULL DEFAULT 0,
  created_at REAL NOT NULL,
  updated_at REAL NOT NULL
);
CREATE INDEX documents_user ON documents(user_id, created_at DESC);
"""

# Same tables and columns; Postgres types. Flags stay 0/1 integers so the SQL
# in the rest of the app is identical on both databases.
_POSTGRES_SCHEMA = """
CREATE TABLE users (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email          TEXT UNIQUE,
  name           TEXT NOT NULL DEFAULT '',
  is_guest       INTEGER NOT NULL DEFAULT 0,
  auth_hash      BYTEA,
  auth_salt      BYTEA,
  kdf_salt       BYTEA,
  kdf_iterations INTEGER,
  wrapped_key    TEXT,
  google_sub     TEXT UNIQUE,
  created_at     DOUBLE PRECISION NOT NULL,
  updated_at     DOUBLE PRECISION NOT NULL
);
CREATE TABLE sessions (
  token_hash TEXT PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at DOUBLE PRECISION NOT NULL,
  expires_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX sessions_user ON sessions(user_id);
CREATE TABLE documents (
  id         TEXT PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  meta       TEXT NOT NULL,
  body       TEXT NOT NULL,
  size       INTEGER NOT NULL,
  starred    INTEGER NOT NULL DEFAULT 0,
  created_at DOUBLE PRECISION NOT NULL,
  updated_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX documents_user ON documents(user_id, created_at DESC);
"""

_ready: set[str] = set()
_lock = threading.Lock()


class Row:
    """A row readable by column name or position and iterable as values,
    like sqlite3.Row, so both databases hand back the same thing."""

    __slots__ = ("_names", "_values")

    def __init__(self, names: Sequence[str], values: Sequence[Any]):
        self._names, self._values = tuple(names), tuple(values)

    def __getitem__(self, key):
        if isinstance(key, (int, slice)):
            return self._values[key]
        try:
            return self._values[self._names.index(key)]
        except ValueError:
            raise KeyError(key) from None

    def __iter__(self):
        return iter(self._values)

    def __len__(self) -> int:
        return len(self._values)

    def keys(self) -> list[str]:
        return list(self._names)

    def __repr__(self) -> str:
        return f"Row({dict(zip(self._names, self._values))!r})"


class Connection:
    """The few calls the app makes, the same on both databases."""

    def __init__(self, raw, postgres: bool):
        self._raw, self._postgres = raw, postgres

    def execute(self, sql: str, params: Sequence[Any] = ()):
        if self._postgres:
            return self._raw.execute(sql.replace("?", "%s"), tuple(params) or None)
        return self._raw.execute(sql, params)

    def insert(self, sql: str, params: Sequence[Any] = ()) -> int:
        """Runs an INSERT and returns the new row's id."""
        return self.execute(f"{sql} RETURNING id", params).fetchall()[0]["id"]


# ---------------------------------------------------------------- SQLite

def _open_sqlite(path: Path) -> sqlite3.Connection:
    con = sqlite3.connect(path, timeout=10)
    con.row_factory = sqlite3.Row
    con.execute("PRAGMA foreign_keys = ON")
    con.execute("PRAGMA secure_delete = ON")
    return con


def _migrate_sqlite(con: sqlite3.Connection) -> None:
    version = con.execute("PRAGMA user_version").fetchone()[0]
    if version >= SCHEMA_VERSION:
        return
    if version == 2:
        # Version 3 adds Google sign-in; every account and document is kept.
        con.execute("ALTER TABLE users ADD COLUMN google_sub TEXT")
        con.execute("CREATE UNIQUE INDEX users_google_sub ON users(google_sub)")
        con.execute(f"PRAGMA user_version = {SCHEMA_VERSION}")
        con.commit()
        return
    tables = {r[0] for r in con.execute("SELECT name FROM sqlite_master WHERE type = 'table'")}
    if tables:
        # Version 1 stored extractions as readable text and hashed raw passwords.
        # Neither can be carried into the encrypted design, so it is removed,
        # and the file is rewritten so no readable copy is left on disk.
        con.executescript("DROP TABLE IF EXISTS papers; DROP TABLE IF EXISTS documents; "
                          "DROP TABLE IF EXISTS sessions; DROP TABLE IF EXISTS users;")
    con.executescript(_SQLITE_SCHEMA)
    con.execute(f"PRAGMA user_version = {SCHEMA_VERSION}")
    con.commit()
    if tables:
        con.execute("VACUUM")


def _prepare_sqlite(path: Path) -> None:
    key = f"sqlite:{path.resolve()}"
    if key in _ready:
        return
    with _lock:
        if key in _ready:
            return
        path.parent.mkdir(parents=True, exist_ok=True)
        con = _open_sqlite(path)
        try:
            _migrate_sqlite(con)
        finally:
            con.close()
        try:
            os.chmod(path, 0o600)     # owner-only on POSIX; ignored on Windows
        except OSError:
            pass
        _ready.add(key)


# ---------------------------------------------------------------- Postgres

_pools: dict[str, Any] = {}


def _row_factory(cursor):
    names = [c.name for c in cursor.description or []]
    return lambda values: Row(names, values)


def _migrate_postgres(con) -> None:
    with con.transaction():
        # One migrator at a time, even with several app instances starting together.
        con.execute("SELECT pg_advisory_xact_lock(7311960)")
        con.execute("CREATE TABLE IF NOT EXISTS schema_version (version INTEGER NOT NULL)")
        row = con.execute("SELECT version FROM schema_version").fetchone()
        version = row[0] if row else 0
        if version >= SCHEMA_VERSION:
            return
        con.execute(_POSTGRES_SCHEMA)
        con.execute("DELETE FROM schema_version")
        con.execute("INSERT INTO schema_version (version) VALUES (%s)", (SCHEMA_VERSION,))


def _pool(url: str):
    pool = _pools.get(url)
    if pool is not None:
        return pool
    with _lock:
        if url in _pools:
            return _pools[url]
        from psycopg_pool import ConnectionPool

        pool = ConnectionPool(
            url, min_size=1, max_size=int(os.getenv("DB_POOL_SIZE", "5")), timeout=15, max_idle=300,
            check=ConnectionPool.check_connection,      # hosted databases drop idle connections
            # prepare_threshold=None: no server-side prepared statements, so
            # pooled URLs (PgBouncer in transaction mode, e.g. Neon's) work.
            kwargs={"row_factory": _row_factory, "prepare_threshold": None}, open=True)
        with pool.connection() as con:
            _migrate_postgres(con)
        _pools[url] = pool
        return pool


def close_pools() -> None:
    """Closes Postgres connections (on shutdown, and between test runs)."""
    with _lock:
        for pool in _pools.values():
            pool.close()
        _pools.clear()


# ---------------------------------------------------------------- one unit of work

def backend() -> str:
    return "postgres" if get_settings().database_url else "sqlite"


@contextmanager
def connect() -> Iterator[Connection]:
    """One transaction: committed if the block finishes, rolled back if it raises."""
    url: Optional[str] = get_settings().database_url
    if url:
        with _pool(url).connection() as raw:      # commits or rolls back on exit
            yield Connection(raw, postgres=True)
        return
    path = get_settings().db_path
    _prepare_sqlite(path)
    raw = _open_sqlite(path)
    try:
        yield Connection(raw, postgres=False)
        raw.commit()
    except BaseException:
        raw.rollback()
        raise
    finally:
        raw.close()
